//! The lock file `requimd.lock` (ADR-0007): review state of links (FR-116)
//! and the highest assigned number per prefix (FR-212, BR-002).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde::Deserialize;

use crate::model::{Item, Target};
use crate::project::{Project, Resolution};

pub const LOCK_FILE: &str = "requimd.lock";

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Lock {
    /// Highest number per prefix ever seen; never decreases.
    pub ids: BTreeMap<String, u64>,
    /// Link key (`<source> <key> <target>`) to the target's content hash
    /// at the last review.
    pub links: BTreeMap<String, String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawLock {
    #[serde(default)]
    ids: BTreeMap<String, u64>,
    #[serde(default)]
    links: BTreeMap<String, String>,
}

impl Lock {
    pub fn parse(text: &str) -> Result<Lock, String> {
        let raw: RawLock =
            toml::from_str(text).map_err(|e| e.to_string().trim_end().to_string())?;
        Ok(Lock {
            ids: raw.ids,
            links: raw.links,
        })
    }

    /// Reads the lock file of a project; a missing file is an empty lock.
    pub fn load(root: &Path) -> Result<Lock, String> {
        match std::fs::read_to_string(root.join(LOCK_FILE)) {
            Ok(text) => Lock::parse(&text).map_err(|e| {
                format!("{e}\nResolve merge conflicts in {LOCK_FILE}, or delete it to record all links anew.")
            }),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Lock::default()),
            Err(e) => Err(e.to_string()),
        }
    }

    /// The file content: sorted, one line per entry.
    pub fn to_toml(&self) -> String {
        let mut out = String::from("# requimd.lock: generated by requimd, commit it.\n");
        out.push_str("\n[ids]\n");
        for (prefix, n) in &self.ids {
            let _ = writeln!(out, "{prefix} = {n}");
        }
        out.push_str("\n[links]\n");
        for (key, hash) in &self.links {
            let _ = writeln!(out, "{} = {}", quote(key), quote(hash));
        }
        out
    }

    /// FR-116, FR-212: the lock after a check. New links get the current
    /// hash, entries of vanished links are removed, `ids` are raised.
    /// Existing hashes are never changed.
    pub fn updated(&self, p: &Project) -> Lock {
        let mut lock = Lock {
            ids: self.ids.clone(),
            links: BTreeMap::new(),
        };
        for item in &p.items {
            let Some(id) = &item.id else { continue };
            if let Some(n) = id
                .strip_prefix(&item.prefix)
                .and_then(|s| s.strip_prefix('-'))
                .and_then(|n| n.parse::<u64>().ok())
            {
                let entry = lock.ids.entry(item.prefix.clone()).or_insert(0);
                *entry = (*entry).max(n);
            }
            let unique = p.declarations(id).len() == 1;
            for link in &item.links {
                let key = link_key(id, &link.key, &link.reference.text);
                if let Some(hash) = self.links.get(&key) {
                    lock.links.insert(key, hash.clone());
                } else if unique
                    && let Some(hash) = link
                        .reference
                        .target
                        .as_ref()
                        .and_then(|t| target_hash(p, t))
                {
                    lock.links.insert(key, hash);
                }
            }
        }
        lock
    }

    /// FR-218, FR-307: marks the suspect links for which `which(source,
    /// target)` holds as reviewed, by recording the current target hash.
    /// Returns the keys of the links marked.
    pub fn review(&mut self, p: &Project, which: impl Fn(&Item, &Target) -> bool) -> Vec<String> {
        let mut marked = Vec::new();
        for item in &p.items {
            let Some(id) = &item.id else { continue };
            for link in &item.links {
                let Some(target) = &link.reference.target else {
                    continue;
                };
                let key = link_key(id, &link.key, &link.reference.text);
                let (Some(reviewed), Some(current)) =
                    (self.links.get(&key), target_hash(p, target))
                else {
                    continue;
                };
                if *reviewed != current && which(item, target) {
                    self.links.insert(key.clone(), current);
                    marked.push(key);
                }
            }
        }
        marked.sort();
        marked.dedup();
        marked
    }

    /// FR-214: the lock with every entry of `old` rewritten to `new`, as
    /// source or as target (also `old.s2`).
    pub fn renamed(&self, old: &str, new: &str) -> Lock {
        let swap = |part: &str| -> String {
            if part == old {
                new.to_string()
            } else if let Some(step) = part.strip_prefix(old).and_then(|r| r.strip_prefix('.')) {
                format!("{new}.{step}")
            } else {
                part.to_string()
            }
        };
        let mut lock = Lock {
            ids: self.ids.clone(),
            links: BTreeMap::new(),
        };
        for (key, hash) in &self.links {
            let parts: Vec<&str> = key.splitn(3, ' ').collect();
            let new_key = match parts.as_slice() {
                [source, k, target] => format!("{} {k} {}", swap(source), swap(target)),
                _ => key.clone(),
            };
            lock.links.insert(new_key, hash.clone());
        }
        lock
    }
}

fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04X}", u32::from(c));
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The lock key of a link, e.g. `FR-104 impl UC-012.s2`.
pub fn link_key(source: &str, key: &str, target: &str) -> String {
    format!("{source} {key} {target}")
}

/// 64-bit FNV-1a of `text` with runs of whitespace as one space, as 16 hex
/// digits. Stable across platforms and Rust versions (ADR-0007).
pub fn hash(text: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    let mut first = true;
    for word in text.split_whitespace() {
        if !first {
            h ^= u64::from(b' ');
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
        first = false;
        for b in word.bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    format!("{h:016x}")
}

/// FR-116: the content of an item that a link depends on: title, metadata
/// except `status`, and body.
fn item_content(p: &Project, item: &Item) -> String {
    let mut s = item.title.clone();
    for m in item.meta.iter().filter(|m| m.key != "status") {
        let _ = write!(s, " {}: {}", m.key, m.value);
    }
    s.push(' ');
    if let Some(body) = p
        .files
        .get(item.file)
        .and_then(|f| f.text.get(item.meta_span.end..item.body.end))
    {
        s.push_str(body);
    }
    s
}

/// The current hash of a link target, `None` if it does not resolve.
pub fn target_hash(p: &Project, target: &Target) -> Option<String> {
    match p.resolve(target) {
        Resolution::Item(i) => Some(hash(&item_content(p, p.items.get(i)?))),
        Resolution::Step(i, s) => {
            let item = p.items.get(i)?;
            let step = item.steps.get(s)?;
            Some(hash(
                p.files.get(item.file)?.text.get(step.text_span.clone())?,
            ))
        }
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;
    use crate::{Config, SourceFile};

    fn project(files: &[(&str, &str)], lock: Lock) -> Project {
        let files = files
            .iter()
            .map(|(n, t)| SourceFile::new(PathBuf::from(n), n.to_string(), t.to_string()))
            .collect();
        let mut p = Project::from_files(PathBuf::from("."), Config::defaults().unwrap(), files);
        p.lock = lock;
        p
    }

    const UC: &str = "## UC-001 U\n\n- s1: Customer pays.\n";
    const FR: &str = "## FR-007 F\nimpl: UC-001.s1  status: draft\n\nThe system shall charge.\n";

    #[test]
    fn fr_116_hash_ignores_whitespace_and_line_endings() {
        assert_eq!(hash("a  b\r\nc"), hash("a b c"));
        assert_ne!(hash("a b"), hash("ab"));
        assert_eq!(hash("").len(), 16);
        // Fixed value, checked against an independent FNV-1a computation:
        // the hash must never change between versions.
        assert_eq!(hash("Customer pays."), "7b2f59d518e62b12");
    }

    #[test]
    fn fr_116_new_links_recorded_existing_hashes_kept_vanished_removed() {
        let p = project(&[("a.md", UC), ("b.md", FR)], Lock::default());
        let lock = Lock::default().updated(&p);
        assert_eq!(lock.ids["FR"], 7);
        assert_eq!(lock.ids["UC"], 1);
        assert_eq!(lock.links.len(), 1);
        let key = "FR-007 impl UC-001.s1";
        assert_eq!(lock.links[key], hash("Customer pays."));

        // An existing hash is kept even if the target changed.
        let mut old = lock.clone();
        old.links.insert(key.into(), "0000000000000000".into());
        old.links
            .insert("FR-007 ref FR-999".into(), "1111111111111111".into());
        old.ids.insert("FR".into(), 50);
        let again = old.updated(&p);
        assert_eq!(again.links[key], "0000000000000000");
        assert!(!again.links.contains_key("FR-007 ref FR-999"));
        assert_eq!(again.ids["FR"], 50, "ids never decrease");
    }

    #[test]
    fn fr_116_no_entries_for_items_without_unique_id() {
        let dup = "## FR-007 G\nimpl: UC-001.s1\n";
        let ph = "## FR-? H\nimpl: UC-001.s1\n";
        let p = project(
            &[("a.md", UC), ("b.md", FR), ("c.md", dup), ("d.md", ph)],
            Lock::default(),
        );
        assert!(Lock::default().updated(&p).links.is_empty());
    }

    #[test]
    fn fr_116_item_hash_covers_title_metadata_body_but_not_status() {
        let target = Target {
            id: "FR-007".into(),
            step: None,
        };
        let h = |fr: &str| {
            target_hash(
                &project(&[("a.md", UC), ("b.md", fr)], Lock::default()),
                &target,
            )
        };
        let base = h(FR);
        assert_eq!(h(&FR.replace("status: draft", "status: review")), base);
        assert_eq!(h(&FR.replace("shall charge.", "shall\ncharge.")), base);
        assert_ne!(h(&FR.replace("charge", "refund")), base);
        assert_ne!(h(&FR.replace("## FR-007 F", "## FR-007 Pay")), base);
        assert_ne!(h(&FR.replace("UC-001.s1", "UC-001")), base);
    }

    #[test]
    fn fr_116_lock_file_roundtrip_is_sorted() {
        let mut lock = Lock::default();
        lock.ids.insert("UC".into(), 12);
        lock.ids.insert("FR".into(), 106);
        lock.links
            .insert("TC-220 ver FR-104".into(), "c07b5e19d3a48f62".into());
        lock.links
            .insert("FR-101 impl UC-012.s1".into(), "8f3a1c0e5b7d2946".into());
        let text = lock.to_toml();
        assert_eq!(
            text,
            "# requimd.lock: generated by requimd, commit it.\n\n[ids]\nFR = 106\nUC = 12\n\n[links]\n\
             \"FR-101 impl UC-012.s1\" = \"8f3a1c0e5b7d2946\"\n\"TC-220 ver FR-104\" = \"c07b5e19d3a48f62\"\n"
        );
        assert_eq!(Lock::parse(&text).unwrap(), lock);
    }

    #[test]
    fn fr_307_review_records_current_hash_of_selected_links() {
        let p = project(&[("a.md", UC), ("b.md", FR)], Lock::default());
        let mut lock = Lock::default().updated(&p);
        let key = "FR-007 impl UC-001.s1";
        lock.links.insert(key.into(), "0000000000000000".into());
        // Not selected: nothing changes.
        assert!(lock.review(&p, |_, t| t.id == "UC-999").is_empty());
        assert_eq!(lock.links[key], "0000000000000000");
        // Selected by target: the link is marked with the current hash.
        assert_eq!(lock.review(&p, |_, t| t.id == "UC-001"), [key]);
        assert_eq!(lock.links[key], hash("Customer pays."));
        // Not suspect any more: a second review marks nothing.
        assert!(lock.review(&p, |_, _| true).is_empty());
    }

    #[test]
    fn fr_214_rename_rewrites_lock_entries() {
        let mut lock = Lock::default();
        lock.links
            .insert("FR-007 impl UC-001.s1".into(), "a".into());
        lock.links.insert("TC-001 ver FR-007".into(), "b".into());
        lock.links.insert("FR-070 ref FR-0071".into(), "c".into());
        let r = lock.renamed("FR-007", "FR-008");
        let keys: Vec<&str> = r.links.keys().map(String::as_str).collect();
        assert_eq!(
            keys,
            [
                "FR-008 impl UC-001.s1",
                "FR-070 ref FR-0071",
                "TC-001 ver FR-008"
            ]
        );
        let r = lock.renamed("UC-001", "UC-002");
        assert!(r.links.contains_key("FR-007 impl UC-002.s1"));
    }

    #[test]
    fn fr_300_conflicted_lock_is_an_error() {
        let conflicted = "[links]\n<<<<<<< HEAD\n\"A impl B\" = \"1\"\n=======\n\"A impl B\" = \"2\"\n>>>>>>> branch\n";
        assert!(Lock::parse(conflicted).is_err());
        assert!(Lock::parse("[other]\nx = 1\n").is_err());
    }
}
